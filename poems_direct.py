if __name__ == "__main__":
    # اختبار القصائد
    poems = load_poems()
    print(f"✅ تم تحميل {len(poems)} قصيدة بنجاح")
    
    # عرض توزيع القصائد حسب المؤلفين
    authors = {}
    for poem in poems:
        author = poem.get("author", "غير محدد")
        if author not in authors:
            authors[author] = []
        authors[author].append(poem["title"])
    
    print("\n📊 توزيع القصائد حسب المؤلفين:")
    for author, titles in authors.items():
        print(f"👤 {author}: {len(titles)} قصيدة")
        for title in titles:
            print(f"   📜 {title}")
        print()
